func typeToTS(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Ptr:
		return typeToTS(t.Elem())
	case reflect.Slice:
		elem := t.Elem()
		if elem.Name() == "byte" || elem.Name() == "uint8" {
			return "number[]"
		}
		if elem.Name() == "ReapDetail" {
			return "ReapDetail[]"
		}
		if elem.Name() == "HistoryTurn" {
			return "HistoryTurn[]"
		}
		if elem.Name() == "MutexSnapshot" {
			return "MutexSnapshot[]"
		}
		if elem.Name() == "SemaphoreSnapshot" {
			return "SemaphoreSnapshot[]"
		}
		return typeToTS(elem) + "[]"
	case reflect.Map:
		key := typeToTS(t.Key())
		val := typeToTS(t.Elem())
		return fmt.Sprintf("Record<%s, %s>", key, val)
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Struct:
		if t.Name() == "FocusInput" {
			return "FocusInput"
		}
		return "any"
	default:
		return "any"
	}
}

func generateInterface(t reflect.Type, name string, typeTag string) string {
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("export interface %s {\n", name))
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		jsonTag := f.Tag.Get("json")
		if jsonTag == "-" || jsonTag == "" {
			continue
		}
		parts := strings.Split(jsonTag, ",")
		jsonName := parts[0]
		isOptional := false
		for _, p := range parts[1:] {
			if p == "omitempty" {
				isOptional = true
			}
		}
		if f.Type.Kind() == reflect.Ptr {
			isOptional = true
		}
		tsType := typeToTS(f.Type)
		opt := ""
		if isOptional {
			opt = "?"
		}
		if jsonName == "type" && typeTag != "" {
			tsType = fmt.Sprintf("'%s'", typeTag)
		}
		sb.WriteString(fmt.Sprintf("  %s%s: %s;\n", jsonName, opt, tsType))
	}
	sb.WriteString("}\n")
	return sb.String()
}

func generateEventInterface(t reflect.Type, name string, tag string) string {
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("export interface %s {\n", name))
	sb.WriteString(fmt.Sprintf("  type: '%s';\n", tag))
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		jsonTag := f.Tag.Get("json")
		if jsonTag == "-" || jsonTag == "" {
			continue
		}
		parts := strings.Split(jsonTag, ",")
		jsonName := parts[0]
		isOptional := false
		for _, p := range parts[1:] {
			if p == "omitempty" {
				isOptional = true
			}
		}
		if f.Type.Kind() == reflect.Ptr {
			isOptional = true
		}
		tsType := typeToTS(f.Type)
		opt := ""
		if isOptional {
			opt = "?"
		}
		if jsonName == "type" && tag != "" {
			tsType = fmt.Sprintf("'%s'", tag)
		}
		sb.WriteString(fmt.Sprintf("  %s%s: %s;\n", jsonName, opt, tsType))
	}
	sb.WriteString("}\n")
	return sb.String()
}
