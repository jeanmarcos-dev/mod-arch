package asm

import (
	"fmt"
)

// SourceLine mirrors programs.SourceLine. We redeclare it here so this package
// can be compiled without importing `programs` (which would cycle through tests).
// The builder's Build() helper converts back to the parent type when the demo
// wires the Proc into the catalogue.
type SourceLine struct {
	Offset   uint32
	Mnemonic string
	CLine    int
}

// VarType is the storage size + display flavour of a declared C variable. The
// simulator reads at most 4 bytes per variable, so this enum stays small.
type VarType string

const (
	VarInt  VarType = "int"  // 4 bytes signed, decimal display
	VarUint VarType = "uint" // 4 bytes unsigned, decimal display
	VarPtr  VarType = "ptr"  // 4 bytes, hex display
	VarChar VarType = "char" // 1 byte, ASCII + hex display
)

// VarLocKind tags the storage class of a Local. Globals always live in memory
// so they use only Addr; Locals can live in any of these.
type VarLocKind string

const (
	VarLocMem   VarLocKind = "mem"   // absolute address (function-scoped global, static)
	VarLocReg   VarLocKind = "reg"   // register (EAX, EBX, ...)
	VarLocStack VarLocKind = "stack" // [EBP + Offset]
)

// VarLoc is a tagged union describing where a variable lives at runtime.
// Exactly one of Addr/Reg/Offset is meaningful, depending on Kind.
type VarLoc struct {
	Kind   VarLocKind
	Addr   uint32 // Kind == VarLocMem
	Reg    string // Kind == VarLocReg (canonical uppercase: "EAX", "EBX", ...)
	Offset int32  // Kind == VarLocStack (signed, typically negative)
}

// Global is a C variable visible in the whole Proc, stored at a fixed address.
type Global struct {
	Name string
	Type VarType
	Addr uint32
	Len  uint32 // size in bytes (4 for int/uint/ptr, 1 for char)
}

// Local is a C variable scoped to a function. The scope is tracked by Func,
// which must match a Func.Name declared in the same Proc.
type Local struct {
	Name string
	Type VarType
	Loc  VarLoc
	Func string
}

// Func marks a callable region inside Proc.Bytes. The simulator uses [Start,
// End) to figure out which function a thread is currently executing (by
// EIP - code_base) so it can resolve the right Locals.
type Func struct {
	Name        string
	StartOffset uint32
	EndOffset   uint32 // exclusive; closed by Build()
}

// Proc is what the builder hands back. It's a plain value object that demos
// embed in their programs.Proc. Build() copies these into the parent type;
// the parent never holds an asm.Builder.
type Proc struct {
	Name      string
	Bytes     []byte
	Source    string
	SourceMap []SourceLine
	Globals   []Global
	Locals    []Local
	Funcs     []Func
}

// Builder accumulates bytes, SourceMap entries and label fixups. It is the
// only stateful object the DSL exposes. Builders are NOT safe for concurrent
// use; one builder per Proc, no sharing.
type Builder struct {
	name      string
	source    string
	bytes     []byte
	sourceMap []SourceLine
	labels    map[string]int
	fixups    []fixup

	// curLine is the C source line every subsequent instruction will map to
	// until .At(n) changes it. 0 means "no line context set" — emitting an
	// instruction in that state panics, because a missing CLine breaks the
	// CodeAsmSplit panel and we want the failure to be obvious during
	// catalogue build, not silently in the UI.
	curLine int
	// curComment is the suffix appended to the auto-mnemonic of the NEXT
	// instruction emitted. Cleared after each instruction so it does not
	// leak. ".Comment()" sets it.
	curComment string

	// globals, locals, funcs accumulate variable / function metadata for the
	// VARS panel. None of these affect generated bytes; they only flow into
	// the snapshot so the UI can resolve "v = 138" by reading the right
	// address or register at runtime. curFunc is the Func that subsequent
	// .Local*() calls attach to; .Func() opens a new one and closes the
	// previous (filling EndOffset).
	globals []Global
	locals  []Local
	funcs   []Func
	curFunc string
}

// NewProc starts a fresh builder under the given Proc name.
func NewProc(name string) *Builder {
	return &Builder{
		name:   name,
		labels: map[string]int{},
	}
}

// Source attaches the C-like text the alumno will see in the simulator. It is
// stored verbatim — no parsing, no transformation.
func (b *Builder) Source(text string) *Builder {
	b.source = text
	return b
}

// At sets the CLine that subsequent instructions map to. The setting is sticky
// until another .At() call. Line numbers are 1-based, matching the SourceMap
// invariant.
func (b *Builder) At(cLine int) *Builder {
	if cLine < 1 {
		panic(fmt.Sprintf("asm: At(%d) must be 1-based", cLine))
	}
	b.curLine = cLine
	return b
}

// Comment sets a suffix that will be appended to the next instruction's
// mnemonic, separated by " ; ". Cleared after that one instruction emits.
// Use to add pedagogical context (e.g. "; load", "; exit code").
func (b *Builder) Comment(text string) *Builder {
	b.curComment = text
	return b
}

// emit appends `enc` to the byte stream and adds one SourceMap entry whose
// mnemonic is `mnem` (plus the pending Comment, if any). Helpers like .Data()
// that produce raw payload bytes bypass this and call b.bytes directly.
func (b *Builder) emit(enc []byte, mnem string) *Builder {
	if b.curLine == 0 {
		panic(fmt.Sprintf("asm: emit %q at offset 0x%X without .At() — set the C line first",
			mnem, len(b.bytes)))
	}
	full := mnem
	if b.curComment != "" {
		full = mnem + " ; " + b.curComment
		b.curComment = ""
	}
	b.sourceMap = append(b.sourceMap, SourceLine{
		Offset:   uint32(len(b.bytes)),
		Mnemonic: full,
		CLine:    b.curLine,
	})
	b.bytes = append(b.bytes, enc...)
	return b
}

// ─── Variable / function metadata ──────────────────────────────────────────

// Global declares a C variable that lives at a fixed address for the lifetime
// of the Proc. It does not emit any bytes; the simulator reads the current
// value at snapshot time. Panics on duplicate name (catching it early during
// catalogue build is cheaper than chasing a wrong popover in the UI).
func (b *Builder) Global(name string, t VarType, addr, length uint32) *Builder {
	if name == "" {
		panic("asm: Global with empty name")
	}
	for _, g := range b.globals {
		if g.Name == name {
			panic(fmt.Sprintf("asm: duplicate Global %q", name))
		}
	}
	b.globals = append(b.globals, Global{Name: name, Type: t, Addr: addr, Len: length})
	return b
}

// Func opens a new function scope starting at the current byte offset. The
// previous open scope (if any) is closed with EndOffset = current offset.
// Subsequent .Local*() calls attach Locals to this function. Panics on
// duplicate function name.
func (b *Builder) Func(name string) *Builder {
	if name == "" {
		panic("asm: Func with empty name")
	}
	for _, f := range b.funcs {
		if f.Name == name {
			panic(fmt.Sprintf("asm: duplicate Func %q", name))
		}
	}
	b.closeCurFunc()
	b.funcs = append(b.funcs, Func{Name: name, StartOffset: uint32(len(b.bytes))})
	b.curFunc = name
	return b
}

// closeCurFunc fills EndOffset on the currently open Func (if any) with the
// current byte offset. Called by Func() when opening a new scope and by
// Build() to close the last one.
func (b *Builder) closeCurFunc() {
	if b.curFunc == "" {
		return
	}
	for i := range b.funcs {
		if b.funcs[i].Name == b.curFunc {
			b.funcs[i].EndOffset = uint32(len(b.bytes))
			return
		}
	}
}

// LocalReg declares a Local that lives in a register. Use for variables a
// hand-written demo keeps in EAX/EBX/… instead of pushing to a stack frame
// (the common case in modos-cpu demos, since they have no compiler).
func (b *Builder) LocalReg(name string, t VarType, reg Reg) *Builder {
	b.addLocal(name, t, VarLoc{Kind: VarLocReg, Reg: reg.String()})
	return b
}

// LocalStack declares a Local at [EBP + ebpOffset]. Use for variables in a
// real call frame (a demo that pushes EBP / MOV EBP, ESP and reserves stack
// space). ebpOffset is signed: locals are typically negative, parameters
// positive.
func (b *Builder) LocalStack(name string, t VarType, ebpOffset int32) *Builder {
	b.addLocal(name, t, VarLoc{Kind: VarLocStack, Offset: ebpOffset})
	return b
}

// LocalMem declares a Local at a fixed address. Use for function-scoped
// statics (a variable visible only inside one function but allocated in the
// data area, like an explicit struct or buffer).
func (b *Builder) LocalMem(name string, t VarType, addr uint32) *Builder {
	b.addLocal(name, t, VarLoc{Kind: VarLocMem, Addr: addr})
	return b
}

func (b *Builder) addLocal(name string, t VarType, loc VarLoc) {
	if name == "" {
		panic("asm: Local with empty name")
	}
	if b.curFunc == "" {
		panic(fmt.Sprintf("asm: Local %q declared before any Func()", name))
	}
	for _, l := range b.locals {
		if l.Func == b.curFunc && l.Name == name {
			panic(fmt.Sprintf("asm: duplicate Local %q in Func %q", name, b.curFunc))
		}
	}
	b.locals = append(b.locals, Local{Name: name, Type: t, Loc: loc, Func: b.curFunc})
}

// ─── Instructions ──────────────────────────────────────────────────────────

// MovImm emits MOV r32, imm32 (B8+rd ib32). Always the 5-byte form.
func (b *Builder) MovImm(dst Reg, imm uint32) *Builder {
	return b.emit(encMovImm32(dst, imm), fmt.Sprintf("MOV %s, 0x%X", dst, imm))
}

// MovReg emits MOV dst, src (89 /r, mod=11).
func (b *Builder) MovReg(dst, src Reg) *Builder {
	return b.emit(encMovRegReg(dst, src), fmt.Sprintf("MOV %s, %s", dst, src))
}

// MovEAXMem emits MOV [addr], EAX (A3). Only EAX is supported as source by
// the underlying ISA.
func (b *Builder) MovEAXMem(addr uint32) *Builder {
	return b.emit(encMovEAXMem(addr), fmt.Sprintf("MOV [0x%X], EAX", addr))
}

// MovMemEAX emits MOV EAX, [addr] (A1). Only EAX is supported as destination.
func (b *Builder) MovMemEAX(addr uint32) *Builder {
	return b.emit(encMovMemEAX(addr), fmt.Sprintf("MOV EAX, [0x%X]", addr))
}

// AddReg emits ADD dst, src.
func (b *Builder) AddReg(dst, src Reg) *Builder {
	return b.emit(encAddRegReg(dst, src), fmt.Sprintf("ADD %s, %s", dst, src))
}

// SubReg emits SUB dst, src.
